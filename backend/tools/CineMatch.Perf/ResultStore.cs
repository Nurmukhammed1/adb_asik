using System.Globalization;
using System.Text;
using System.Text.Json;

namespace CineMatch.Perf;

/// <summary>
/// Keeps every measurement as a JSON file and rebuilds the readable summary from all of them:
///   datasets/&lt;dataset&gt;.json      timings of loading a dataset
///   runs/&lt;stage&gt;/&lt;dataset&gt;.json  one measurement run
///   summary.md, latency.csv, query-plans.csv
/// </summary>
public sealed class ResultStore(string directory)
{
    private static readonly string[] DatasetOrder = ["small", "1m", "10m", "32m"];
    private static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web) { WriteIndented = true };
    private static readonly CultureInfo Invariant = CultureInfo.InvariantCulture;

    public string Directory { get; } = directory;

    public void Save(PrepareResult result) =>
        Write(Path.Combine(Directory, "datasets", $"{result.Dataset}.json"), JsonSerializer.Serialize(result, Json));

    public void Save(RunResult result) =>
        Write(Path.Combine(Directory, "runs", result.Stage, $"{result.Dataset}.json"), JsonSerializer.Serialize(result, Json));

    public List<PrepareResult> LoadPrepared() =>
        Load<PrepareResult>(Path.Combine(Directory, "datasets")).OrderBy(p => DatasetRank(p.Dataset)).ToList();

    public List<RunResult> LoadRuns() =>
        Load<RunResult>(Path.Combine(Directory, "runs")).OrderBy(r => r.MeasuredAt).ToList();

    /// <summary>Rewrites summary.md and the CSV files from everything stored so far.</summary>
    public void WriteSummary()
    {
        var prepared = LoadPrepared();
        var runs = LoadRuns();
        Write(Path.Combine(Directory, "summary.md"), BuildMarkdown(prepared, runs));
        Write(Path.Combine(Directory, "latency.csv"), BuildLatencyCsv(runs));
        Write(Path.Combine(Directory, "query-plans.csv"), BuildPlansCsv(runs));
    }

    // ---------- Markdown ----------

    public static string BuildMarkdown(IReadOnlyList<PrepareResult> prepared, IReadOnlyList<RunResult> runs)
    {
        var md = new StringBuilder();
        md.AppendLine("# CineMatch performance results");
        md.AppendLine();
        md.AppendLine("Generated by `tools/CineMatch.Perf` from the JSON files in this folder. Do not edit by hand:");
        md.AppendLine("run the tool again instead.");

        var machine = runs.LastOrDefault()?.Machine ?? prepared.LastOrDefault()?.Machine;
        if (machine is not null)
        {
            md.AppendLine();
            md.AppendLine("## Test machine");
            md.AppendLine();
            md.AppendLine(F($"- {machine.Cores} logical cores, {machine.MemoryGb} GB of memory, {machine.Os}"));
            md.AppendLine(F($"- {machine.Runtime}, MongoDB {machine.MongoVersion} (one-node replica set in Docker)"));
            md.AppendLine("- The API, MongoDB and the benchmark tool all run on this one machine.");
        }

        if (prepared.Count > 0)
        {
            md.AppendLine();
            md.AppendLine("## Loading the data and building the similarity table");
            md.AppendLine();
            md.AppendLine("Times in seconds. \"Import\" is the whole import; the next three columns are parts of it.");
            md.AppendLine();
            md.AppendLine("| Dataset | Movies | Users | Ratings | Import | Insert ratings | Rating stats | Build indexes | Similarity: load | build | save | Movies with neighbors | Data (MB) | Indexes (MB) |");
            md.AppendLine("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|");
            foreach (var p in prepared)
            {
                md.AppendLine(F($"| {p.Dataset} | {p.Import.Movies:N0} | {p.Import.Users:N0} | {p.Import.Ratings:N0} | {p.Import.TotalSeconds:0.0} | {p.Import.RatingsSeconds:0.0} | {p.Import.RatingStatsSeconds:0.0} | {p.Import.IndexSeconds:0.0} | {p.Similarity.LoadSeconds:0.0} | {p.Similarity.BuildSeconds:0.0} | {p.Similarity.SaveSeconds:0.0} | {p.Similarity.MoviesWithNeighbors:N0} | {p.Data.DataMb:N0} | {p.Data.IndexMb:N0} |"));
            }
        }

        var stages = runs.Select(r => r.Stage).Distinct().ToList();   // in the order they were first measured
        var datasets = runs.Select(r => r.Dataset).Distinct().OrderBy(DatasetRank).ToList();
        var scenarios = runs.SelectMany(r => r.Latency).Select(l => (l.Scenario, l.Description)).DistinctBy(s => s.Scenario).ToList();
        RunResult? Run(string stage, string dataset) => runs.LastOrDefault(r => r.Stage == stage && r.Dataset == dataset);

        if (runs.Count > 0)
        {
            md.AppendLine();
            md.AppendLine("## Response times");
            md.AppendLine();
            md.AppendLine("Milliseconds, measured at the client for requests sent one after another. Each cell is");
            md.AppendLine("**median / 95th percentile** (95% of requests were at least this fast).");

            foreach (var stage in stages)
            {
                md.AppendLine();
                md.AppendLine($"### Stage: {stage}");
                md.AppendLine();
                md.AppendLine("| Request | " + string.Join(" | ", datasets.Select(d => DatasetTitle(d, Run(stage, d)))) + " |");
                md.AppendLine("|---|" + string.Concat(datasets.Select(_ => "---:|")));
                foreach (var (scenario, description) in scenarios)
                {
                    var cells = datasets.Select(d => LatencyCell(Run(stage, d)?.Latency.FirstOrDefault(l => l.Scenario == scenario)));
                    md.AppendLine($"| {description} (`{scenario}`) | " + string.Join(" | ", cells) + " |");
                }
            }

            foreach (var dataset in datasets)
            {
                var measured = stages.Where(s => Run(s, dataset) is not null).ToList();
                if (measured.Count < 2) continue;

                md.AppendLine();
                md.AppendLine($"### Stages compared on dataset {dataset}");
                md.AppendLine();
                md.AppendLine($"95th percentile in milliseconds. The last column is the first stage divided by the last.");
                md.AppendLine();
                md.AppendLine("| Request | " + string.Join(" | ", measured) + " | Speed-up |");
                md.AppendLine("|---|" + string.Concat(measured.Select(_ => "---:|")) + "---:|");
                foreach (var (scenario, description) in scenarios)
                {
                    var values = measured
                        .Select(s => Run(s, dataset)!.Latency.FirstOrDefault(l => l.Scenario == scenario))
                        .ToList();
                    var cells = values.Select(v => v is null ? "–" : v.Requests == v.Errors ? "failed" : F($"{v.P95Ms:0.0}"));
                    md.AppendLine($"| {description} | " + string.Join(" | ", cells) + $" | {SpeedUp(values[0], values[^1])} |");
                }
            }

            md.AppendLine();
            md.AppendLine("## Test users");
            md.AppendLine();
            md.AppendLine("Requests that need a login use imported accounts picked by their number of ratings.");
            md.AppendLine();
            md.AppendLine("| Dataset | \"Typical\" users | Their ratings (median user) | \"Heavy\" users | Ratings of the heaviest |");
            md.AppendLine("|---|---:|---:|---:|---:|");
            foreach (var dataset in datasets)
            {
                var users = runs.Last(r => r.Dataset == dataset).Users;
                md.AppendLine(F($"| {dataset} | {users.TypicalUsers} | {users.TypicalRatings:N0} | {users.HeavyUsers} | {users.HeaviestRatings:N0} |"));
            }

            md.AppendLine();
            md.AppendLine("## Query plans");
            md.AppendLine();
            md.AppendLine("How MongoDB executed the API's main queries. \"Examined\" far above \"returned\" means the");
            md.AppendLine("query read documents it did not need; `COLLSCAN` means it read the whole collection.");
            foreach (var stage in stages)
            {
                foreach (var dataset in datasets)
                {
                    if (Run(stage, dataset) is not { } run) continue;
                    md.AppendLine();
                    md.AppendLine(F($"### {stage}, dataset {dataset} ({run.Data.Ratings:N0} ratings)"));
                    md.AppendLine();
                    md.AppendLine("| Query | Collection | Docs examined | Index keys examined | Returned | Server ms | Plan |");
                    md.AppendLine("|---|---|---:|---:|---:|---:|---|");
                    foreach (var plan in run.Plans)
                    {
                        md.AppendLine(F($"| {plan.Query} | {plan.Collection} | {plan.DocsExamined:N0} | {plan.KeysExamined:N0} | {plan.Returned:N0} | {plan.ServerMillis:N0} | {plan.Plan.Replace("|", "\\|")} |"));
                    }
                }
            }

            var notes = runs
                .SelectMany(r => r.Latency.Where(l => l.Note is not null || l.Errors > 0).Select(l => (r.Stage, r.Dataset, Result: l)))
                .ToList();
            if (notes.Count > 0)
            {
                md.AppendLine();
                md.AppendLine("## Notes");
                md.AppendLine();
                foreach (var (stage, dataset, result) in notes)
                {
                    md.AppendLine(F($"- {stage}, {dataset}, `{result.Scenario}`: {result.Requests} requests, {result.Errors} failed{(result.Note is null ? "" : $" ({result.Note})")}."));
                }
            }
        }

        return md.ToString();
    }

    private static string DatasetTitle(string dataset, RunResult? run) =>
        run is null ? dataset : F($"{dataset} ({run.Data.Ratings:N0} ratings)");

    private static string LatencyCell(LatencyResult? result) => result switch
    {
        null => "–",
        { Requests: var requests, Errors: var errors } when requests == errors => "failed",
        _ => F($"{result.P50Ms:0.0} / {result.P95Ms:0.0}"),
    };

    private static string SpeedUp(LatencyResult? first, LatencyResult? last) =>
        first is null || last is null || first.Requests == first.Errors || last.Requests == last.Errors || last.P95Ms <= 0
            ? "–"
            : F($"{first.P95Ms / last.P95Ms:0.0}x");

    // ---------- CSV ----------

    public static string BuildLatencyCsv(IEnumerable<RunResult> runs)
    {
        var csv = new StringBuilder("stage,dataset,ratings,scenario,requests,errors,min_ms,p50_ms,p95_ms,p99_ms,max_ms,mean_ms,note\n");
        foreach (var run in runs)
        {
            foreach (var l in run.Latency)
            {
                csv.Append(F($"{Csv(run.Stage)},{run.Dataset},{run.Data.Ratings},{l.Scenario},{l.Requests},{l.Errors},{l.MinMs},{l.P50Ms},{l.P95Ms},{l.P99Ms},{l.MaxMs},{l.MeanMs},{Csv(l.Note ?? "")}\n"));
            }
        }
        return csv.ToString();
    }

    public static string BuildPlansCsv(IEnumerable<RunResult> runs)
    {
        var csv = new StringBuilder("stage,dataset,ratings,query,collection,docs_examined,keys_examined,returned,server_ms,plan\n");
        foreach (var run in runs)
        {
            foreach (var p in run.Plans)
            {
                csv.Append(F($"{Csv(run.Stage)},{run.Dataset},{run.Data.Ratings},{Csv(p.Query)},{p.Collection},{p.DocsExamined},{p.KeysExamined},{p.Returned},{p.ServerMillis},{Csv(p.Plan)}\n"));
            }
        }
        return csv.ToString();
    }

    private static string Csv(string value) =>
        value.IndexOfAny([',', '"', '\n']) < 0 ? value : "\"" + value.Replace("\"", "\"\"") + "\"";

    // ---------- Files ----------

    private static int DatasetRank(string dataset)
    {
        var rank = Array.IndexOf(DatasetOrder, dataset);
        return rank < 0 ? int.MaxValue : rank;
    }

    /// <summary>Formats numbers the same way on every machine (a point as the decimal separator).</summary>
    private static string F(FormattableString text) => text.ToString(Invariant);

    private static List<T> Load<T>(string folder) =>
        !System.IO.Directory.Exists(folder)
            ? []
            : System.IO.Directory.EnumerateFiles(folder, "*.json", SearchOption.AllDirectories)
                .Select(file => JsonSerializer.Deserialize<T>(File.ReadAllText(file), Json)!)
                .ToList();

    private static void Write(string path, string content)
    {
        System.IO.Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content.ReplaceLineEndings("\n"), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
    }
}
